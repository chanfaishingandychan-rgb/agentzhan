export function getLearnTask(slug: string) {
  return learnTasks.find((task) => task.slug === slug || String(task.day) === slug);
}

export function getNextLearnTask(day: number) {
  return learnTasks.find((task) => task.day === day + 1);
}

export function getPreviousLearnTask(day: number) {
  return learnTasks.find((task) => task.day === day - 1);
}
